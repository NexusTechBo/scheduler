CREATE TABLE IF NOT EXISTS public.clinics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    phone_number VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    activated_at TIMESTAMP NULL,
    CONSTRAINT uq_clinics_slug UNIQUE (slug)
);

CREATE TABLE IF NOT EXISTS public.clinic_activation_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinic_id BIGINT NOT NULL REFERENCES public.clinics(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL,
    email VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    used_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_clinic_activation_tokens_token_hash UNIQUE (token_hash)
);

CREATE INDEX IF NOT EXISTS idx_clinic_activation_tokens_clinic ON public.clinic_activation_tokens(clinic_id);
CREATE INDEX IF NOT EXISTS idx_clinic_activation_tokens_email ON public.clinic_activation_tokens(LOWER(email));
